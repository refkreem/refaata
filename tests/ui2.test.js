// اختبار: فواصل الآلاف، الدفعة المقدمة كإيراد، رقم الفاتورة التلقائي، متبقي المورد
const { chromium } = require('playwright');
const path = require('path');
let fails = 0, passes = 0;
function ck(n, c, x) { if (c) { passes++; console.log('  ✔', n); } else { fails++; console.log('  ✘', n, x === undefined ? '' : JSON.stringify(x)); } }
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
  const pg = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
  pg.on('pageerror', e => { fails++; console.log('   PAGEERR', e.message); });
  pg.on('dialog', d => d.accept());
  await pg.route(/gstatic|cdnjs|googleapis/, r => r.abort());
  await pg.goto('file://' + path.resolve(__dirname, '../index.html'));
  await pg.waitForFunction(() => window.S && S.db);
  const ev = (f, a) => pg.evaluate(f, a);
  const set = (s, v) => pg.fill(s, String(v));
  const save = async () => { await pg.click('#msaveBtn'); await pg.waitForTimeout(200); };
  await pg.click('#side a[data-p=accounts]'); await pg.click('[data-a=accAdd][data-p=cash]'); await set('#a_name', 'الخزينة'); await set('#a_open', 100); await save();
  await pg.click('[data-a=accAdd][data-p=bank]'); await set('#a_name', 'بنك مصر'); await set('#a_open', 0); await save();
  const cash = await ev(() => S.accounts.find(a => a.kind === 'cash').id), bank = await ev(() => S.accounts.find(a => a.kind === 'bank').id);
  console.log('الدفعة المقدمة وفواصل الآلاف');
  await pg.click('#side a[data-p=projects]'); await pg.click('[data-a=projAdd]');
  await set('#p_name', 'مشروع أ'); await set('#p_months', 6); await set('#p_val', 1234567);
  ck('فواصل الآلاف تظهر أثناء الكتابة', (await ev(() => $('p_val').value)) === '1,234,567');
  ck('التأمين التلقائي بفواصل', (await ev(() => $('p_bi').value)) === '12,345.67');
  await set('#p_adv', 250000);
  await save();
  ck('بدون حساب لا يُحفظ المشروع', (await ev(() => S.projects.length)) === 0);
  await pg.selectOption('#f_pm', 'تحويل بنكي');
  ck('طريقة تحويل بنكي تعرض البنوك فقط', (await ev(() => [...$('f_acc').options].filter(o => o.value).map(o => o.value))).join() === bank);
  await pg.selectOption('#f_acc', bank); await set('#f_ref', 'TR-77'); await save();
  const P = await ev(() => S.projects[0]);
  ck('قيم رقمية صحيحة', P.value === 1234567 && P.advance === 250000, P);
  const R = await ev(() => S.txs.filter(t => t.type === 'revenue'));
  ck('الدفعة المقدمة سُجلت إيرادًا في البنك', R.length === 1 && R[0].amount === 250000 && R[0].account_id === bank && R[0].kind === 'دفعة مقدمة' && R[0].pay_method === 'تحويل بنكي' && R[0].ref === 'TR-77', R);
  ck('رصيد البنك زاد', (await ev(() => accStats(S.accounts.find(a => a.kind === 'bank')).bal)) === 250000);
  ck('المحصّل يشمل الدفعة', (await ev(id => projTotals(id).revenue, P.id)) === 250000);
  await ev(id => { S.vp = id; render(); ACT.projEdit(id); }, P.id);
  ck('التعديل يملأ الحساب والمرجع', (await ev(() => $('f_acc').value)) === bank && (await ev(() => $('f_ref').value)) === 'TR-77' && (await ev(() => $('p_adv').value)) === '250,000');
  await set('#p_adv', 300000); await pg.selectOption('#f_pm', 'نقدي'); await pg.selectOption('#f_acc', cash); await save();
  const R2 = await ev(() => S.txs.filter(t => t.type === 'revenue'));
  ck('التعديل يحدّث نفس الإيراد (لا تكرار)', R2.length === 1 && R2[0].amount === 300000 && R2[0].account_id === cash, R2);
  console.log('رقم الفاتورة والمتبقي للمورد');
  await pg.click('#side a[data-p=purchases]'); await pg.click('[data-a=newTx][data-p="purchase|"]');
  await pg.waitForTimeout(100);
  await pg.selectOption('#t_proj', P.id); await set('#t_sup', 'مورد س');
  ck('أول فاتورة للمورد = 1', (await ev(() => $('t_inv').value)) === '1');
  await pg.fill('.l_item', 'كابل'); await pg.fill('.l_qty', '10'); await pg.fill('.l_price', '1500'); await set('#t_paid', 5000);
  ck('الإجمالي بفواصل في الشاشة', (await ev(() => $('s_total').textContent)) === '15,000');
  await pg.selectOption('#f_acc', cash);
  ck('رصيد المورد يظهر', (await ev(() => $('suphint').innerText)).includes('10,000'));
  await save();
  await pg.click('[data-a=newTx][data-p="purchase|"]'); await pg.waitForTimeout(100);
  await set('#t_sup', 'مورد س');
  ck('الفاتورة التالية = 2', (await ev(() => $('t_inv').value)) === '2');
  await set('#t_sup', 'مورد ص');
  ck('مورد آخر يبدأ من 1', (await ev(() => $('t_inv').value)) === '1');
  await set('#t_inv', 'A-9'); await set('#t_sup', 'مورد س');
  ck('الرقم اليدوي لا يُستبدل', (await ev(() => $('t_inv').value)) === 'A-9');
  await ev(() => closeModal());
  await pg.click('[data-a=newTx][data-p="payment|supplier"]'); await pg.waitForTimeout(100);
  await pg.selectOption('#t_sup', 'مورد س'); await set('#t_amt', 4000); await pg.waitForTimeout(100);
  const hint = await ev(() => $('itemhint').innerText);
  ck('متبقي المورد في السداد وبعده', hint.includes('10,000') && hint.includes('6,000'), hint);
  console.log('التخصص وفحص الترابط'); await ev(() => closeModal());
  await pg.click('#side a[data-p=settings]'); await pg.click('[data-a=setSec][data-p=suppliers]');
  await pg.click('[data-a=supEdit][data-p="0"]'); await set('#sp_t', 'كهرباء'); await set('#sp_p', '0100'); await save();
  ck('تخصص المورد يُحفظ ويظهر', (await ev(() => S.cfg.supInfo['مورد س'].trade)) === 'كهرباء' && (await ev(() => document.querySelector('#main').innerText)).includes('كهرباء'));
  await pg.click('[data-a=setSec][data-p=workers]'); await pg.click('[data-a=wAdd]'); await set('#w_n', 'أشرف'); await set('#w_t', 'فني تكييف'); await set('#w_r', 400); await save();
  ck('تخصص العامل يُحفظ', (await ev(() => S.cfg.workers.find(w => w.name === 'أشرف').trade)) === 'فني تكييف');
  await ev(id => { proj(id).boq = [{ id: 'bq', code: '1', name: 'بند', unit: 'م', qty: 10, price: 100 }]; }, P.id);
  const rep = await ev(() => REPS.links.run({}));
  ck('فحص الترابط يكشف صنف المورد غير المرتبط ببند', rep.rows.some(r => r[5].includes('غير مرتبط ببند')), rep.rows);
  await ev(id => { S.vp = id; S.tab = 'boq'; S.view = 'projects'; render(); }, P.id);
  ck('شريط ترابط التكلفة يظهر في المشروع', (await ev(() => document.querySelector('#main').innerText)).includes('ترابط التكلفة'));
  const pr = await ev(() => REPS.profit.run({}));
  ck('تقرير الربحية يتضمن حصة المصروفات العامة', pr.cols.some(c => c.h.includes('المصروفات العامة')));
  console.log(passes + ' نجح، ' + fails + ' فشل'); await b.close(); process.exit(fails ? 1 : 0);
})();
